const __filename = fileURLToPath(import.meta.url);
const __dirname = path.dirname(__filename);

// 创建结果输出文件
const outputFile = path.join(__dirname, 'load_test_results.json');

// 压力测试主函数
async function main() {
    console.log('开始执行所有查询');
    console.log(`查询列表包含 ${queryList.length} 个查询`);
    console.log(`结果将保存到: ${outputFile}`);
    console.log(`最大并发数: 20`);

    const results = [];
    const startTime = Date.now();
    const maxConcurrent = 20;
    let queryIndex = 0;
    let totalRequests = queryList.length;
    let completedRequests = 0;
    let errorCount = 0;
    let activeRequests = 0;

    return new Promise(async (resolve) => {
        const executeNext = async () => {
            // 所有请求都已启动
            if (queryIndex >= queryList.length) {
                // 等待所有活动请求完成
                if (activeRequests === 0) {
                    console.log('\n所有请求完成!');
                    await saveResults(results, completedRequests, errorCount, totalRequests);
                    resolve();
                }
                return;
            }

            // 达到最大并发限制
            if (activeRequests >= maxConcurrent) {
                return;
            }

            const currentIndex = queryIndex;
            const query = queryList[currentIndex];
            queryIndex++;
            activeRequests++;

            // 跳过空查询
            if (!query || !query.trim()) {
                activeRequests--;
                executeNext();
                return;
            }

            executeRequest(query, currentIndex + 1)
                .then(result => {
                    completedRequests++;
                    results.push(result);
                    if (completedRequests % 50 === 0) {
                        console.log(`已完成 ${completedRequests}/${totalRequests} 个请求`);
                    }
                })
                .catch(error => {
                    errorCount++;
                    const errorResult = {
                        requestId: currentIndex + 1,
                        query: query,
                        error: errorStringify(error),
                        timestamp: new Date().toISOString(),
                        success: false
                    };
                    results.push(errorResult);
                    console.error(`请求 ${currentIndex + 1} 失败:`, errorStringify(error));
                })
                .finally(() => {
                    activeRequests--;
                    executeNext(); // 完成一个后继续下一个
                });

            // 启动下一个请求
            executeNext();
        };

        // 启动初始并发请求
        for (let i = 0; i < maxConcurrent && i < queryList.length; i++) {
            executeNext();
        }
    });
}

// 执行单个请求
async function executeRequest(query, requestId) {
    const requestStart = Date.now();

    try {
        // 创建新的参数对象，避免修改全局对象
        const requestParams = JSON.parse(JSON.stringify(params));
        requestParams.recent_messages.push({ role: "user", content: [{ type: "text", text: query }] });
        console.log(999999, requestParams.recent_messages.length)
        const response = await fetch('http://localhost:8082/agent/v1/chat/completion/stream', {
            method: 'POST',
            body: JSON.stringify(requestParams),
            headers: {
                ...header,
                [TraceIDHeaderKey]: `load-test-${requestId}-${Date.now()}`
            },
        });

        const reader = response.body?.getReader();
        if (!reader) {
            throw new Error('No response body reader available');
        }

        const decoder = new TextDecoder();
        let done = false;
        let text = '';

        while (!done) {
            const { value, done: readerDone } = await reader.read();
            if (value) {
                text += decoder.decode(value, { stream: true });
            }
            done = readerDone;
        }

        const requestEnd = Date.now();
        const duration = requestEnd - requestStart;

        return {
            requestId: requestId,
            query: query,
            response: text,
            duration: duration,
            timestamp: new Date().toISOString(),
            success: true,
            statusCode: response.status
        };

    } catch (error) {
        const requestEnd = Date.now();
        const duration = requestEnd - requestStart;

        throw {
            requestId: requestId,
            query: query,
            error: errorStringify(error),
            duration: duration,
            timestamp: new Date().toISOString(),
            success: false
        };
    }
}

// 保存测试结果
async function saveResults(results, completedRequests, errorCount, totalRequests) {
    const successfulResults = results.filter(r => r.success && r.duration);
    const summary = {
        testSummary: {
            totalRequests: totalRequests,
            completedRequests: completedRequests,
            errorCount: errorCount,
            successRate: ((completedRequests - errorCount) / completedRequests * 100).toFixed(2) + '%',
            startTime: new Date().toISOString()
        },
        performance: {
            averageResponseTime: successfulResults.length > 0
                ? successfulResults.reduce((sum, r) => sum + r.duration, 0) / successfulResults.length
                : 0,
            minResponseTime: successfulResults.length > 0
                ? Math.min(...successfulResults.map(r => r.duration))
                : 0,
            maxResponseTime: successfulResults.length > 0
                ? Math.max(...successfulResults.map(r => r.duration))
                : 0
        },
        results: results
    };

    try {
        await fs.promises.writeFile(outputFile, JSON.stringify(summary, null, 2), 'utf8');
        console.log('\n========== 压力测试总结 ==========');
        console.log(`总请求数: ${totalRequests}`);
        console.log(`完成请求数: ${completedRequests}`);
        console.log(`错误数: ${errorCount}`);
        console.log(`成功率: ${summary.testSummary.successRate}`);
        console.log(`平均响应时间: ${summary.performance.averageResponseTime.toFixed(2)}ms`);
        console.log(`最小响应时间: ${summary.performance.minResponseTime}ms`);
        console.log(`最大响应时间: ${summary.performance.maxResponseTime}ms`);
        console.log(`结果已保存到: ${outputFile}`);
        console.log('================================');
    } catch (error) {
        console.error('保存结果文件失败:', error);
    }
}

